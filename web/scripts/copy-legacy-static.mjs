// Post-build: copy the repo-root static passthrough into web/dist/ so the Vite
// build is self-contained.
//
// Images, data feeds, PWA files, and error pages are referenced by absolute
// paths (/assets/images/..., /data/news.json, /version.json, ...) but live at
// the repo root, not inside the Vite app. In dev, serve-legacy-static.ts serves
// them; for the cPanel build, build.sh stage 4c copies them into dist/. This
// mirrors that copy so any consumer of web/dist/ (Vercel, `npm run preview`)
// gets a complete site.
//
// Kept in sync with build.sh stage 4c and the prefixes in
// web/vite-plugins/serve-legacy-static.ts. Skips .htaccess (Vercel ignores it)
// and sitemap.xml (generated by build.sh, not present at the root).
import { cpSync, existsSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// This file lives at web/scripts/, so the repo root is two levels up.
const repoRoot = fileURLToPath(new URL('../../', import.meta.url));
const distDir = fileURLToPath(new URL('../dist/', import.meta.url));

// Directories copied recursively, and single files copied as-is.
// admin/ (internal news editor) and data/ subdirectories (build-time sources)
// are intentionally excluded — only top-level data/*.json feeds are deployed.
const ENTRIES = [
  'assets',
  'version.json',
  'sw.js',
  'manifest.webmanifest',
  'robots.txt',
  'offline.html',
  '403.html',
  '404.html',
  '500.html',
];

if (!existsSync(distDir)) {
  console.error(`copy-legacy-static: ${distDir} does not exist — run the build first.`);
  process.exit(1);
}

let copied = 0;
for (const entry of ENTRIES) {
  const src = path.join(repoRoot, entry);
  if (!existsSync(src)) {
    console.warn(`  skip (missing): ${entry}`);
    continue;
  }
  cpSync(src, path.join(distDir, entry), { recursive: true });
  copied += 1;
  console.log(`  copied: ${entry}`);
}

// data/: copy only the top-level JSON feeds the site fetches at runtime
// (/data/news.json, /data/officials.json, ...). Subdirectories like data/mati/
// hold build-time sources (scripts, CSVs, docs) that must not ship.
const dataSrc = path.join(repoRoot, 'data');
const dataDest = path.join(distDir, 'data');
if (existsSync(dataSrc)) {
  mkdirSync(dataDest, { recursive: true });
  let feeds = 0;
  for (const name of readdirSync(dataSrc)) {
    const abs = path.join(dataSrc, name);
    if (!statSync(abs).isFile() || !name.endsWith('.json')) continue;
    cpSync(abs, path.join(dataDest, name));
    feeds += 1;
  }
  console.log(`  copied: data/*.json (${feeds} feeds)`);
  copied += 1;
} else {
  console.warn('  skip (missing): data');
}
console.log(`copy-legacy-static: ${copied}/${ENTRIES.length + 1} entries → web/dist/`);
